 id TEXT PRIMARY KEY,
 provider TEXT NOT NULL CHECK (provider IN ('kaabag','gemini','groq','cloudflare','mistral','cohere','openrouter')),
 label TEXT NOT NULL DEFAULT '',
 model TEXT NOT NULL DEFAULT '',
 key_ciphertext TEXT NOT NULL DEFAULT '',
 key_hint TEXT NOT NULL DEFAULT '',
 enabled BOOLEAN NOT NULL DEFAULT TRUE,
 priority INTEGER NOT NULL DEFAULT 100 CHECK (priority BETWEEN 0 AND 10000),
 created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
 updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_ai_provider_order ON portfolio.ai_provider_configs(enabled,priority,id);

